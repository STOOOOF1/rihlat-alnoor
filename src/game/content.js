/** Pick quiz questions for a stage by difficulty (0..2). */
export function pickQuiz(id, diff) {
  const all = QUIZ[id];
  const n = [3, 4, 5][diff];
  const by = (l) => shuffle(all.filter((q) => q.l === l));
  const order = diff === 0 ? [...by(0), ...by(1)] : diff === 1 ? [...by(1), ...by(0), ...by(2)] : [...by(2), ...by(1), ...by(0)];
  return shuffle(order.slice(0, n));
}

